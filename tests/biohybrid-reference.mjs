import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { runSimulation, MODEL_VERSION } from '../src/lib/biohybrid/model.js';

const report = JSON.parse(readFileSync(new URL('../docs/biohybrid/neuron-validation.json', import.meta.url), 'utf8'));
const sha256 = content => createHash('sha256').update(content).digest('hex');
const max = values => values.reduce((a, b) => Math.max(a, b), 0);

// The native simulator is intentionally absent from ordinary browser builds.
// This fixture was generated by the independently executed native NEURON script.
// Pin the exact audited source and physical inputs, then compare current JS
// outputs to the native samples without alignment or numerical rescaling.
test('Biohybrid independent reference provenance and unchanged acceptance gates', () => {
  assert.equal(report.schema, 'biohybrid-neuron-validation/1');
  assert.equal(report.modelVersion, MODEL_VERSION);
  assert.equal(report.reference.name, 'NEURON');
  assert.equal(report.reference.version, '9.0.1');
  assert.equal(report.criteria.rootMeanSquareVoltageMv, 1);
  assert.equal(report.criteria.maximumSpikeTimingErrorMs, .1);
  assert.equal(report.criteria.strictPointwiseVoltageMv, .5);
  assert.equal(report.criteria.extracellularMaximumErrorUv, .001);
  assert.equal(report.criteria.sourceComponentMaximumErrorUv, .001);
  assert.equal(report.observationVersion, 'biohybrid-source-observations/1.0.0');
  assert.equal(report.allAcceptancePassed, true);
  assert.equal(report.strictPointwiseAllPassed, true);
  assert.equal(report.cases.length, 4);
  for (const [path, expected] of Object.entries(report.sourceSha256)) {
    assert.equal(sha256(readFileSync(new URL(`../${path}`, import.meta.url))), expected,
      `${path} changed after native validation; regenerate the independent reference.`);
  }
  assert.equal(sha256(readFileSync(new URL('../scripts/biohybrid/neuron-reference.py', import.meta.url))), report.referenceScriptSha256);
  assert.ok(report.developmentDiscrepancies.some(item => item.caseId === 'relay-dt0025'));
});

for (const reference of report.cases) {
  test(`Biohybrid matches native NEURON: ${reference.id}`, () => {
    const result = runSimulation(reference.settings);
    const inputSha256 = sha256(JSON.stringify({ settings: result.settings, geometry: result.geometry, restMv: result.diagnostics.restMv }));
    assert.equal(inputSha256, reference.inputSha256, 'The physical model inputs differ from those used by the native reference.');
    assert.deepEqual(Array.from(result.timeMs), reference.timeMs);
    assert.equal(reference.acceptancePassed, true);
    for (const [check, passed] of Object.entries(reference.checks)) assert.equal(passed, true, check);
    for (const trace of reference.traces) {
      const actual = result.traces.find(item => item.id === trace.id);
      assert.ok(actual, trace.id);
      assert.equal(actual.values.length, trace.nativeVoltageMv.length);
      const errors = Array.from(actual.values, (value, i) => value - trace.nativeVoltageMv[i]);
      const rms = Math.sqrt(errors.reduce((sum, error) => sum + error * error, 0) / errors.length);
      assert.ok(rms <= report.criteria.rootMeanSquareVoltageMv, `${trace.id}: RMS ${rms} mV`);
      assert.ok(max(errors.map(Math.abs)) <= report.criteria.strictPointwiseVoltageMv,
        `${trace.id}: strict pointwise membrane criterion failed`);
    }
    for (const monitor of reference.spikes) {
      const actual = result.spikes.filter(spike => spike.neuronId === monitor.neuronId && spike.kind === monitor.kind).map(spike => spike.timeMs);
      assert.equal(actual.length, monitor.nativeTimesMs.length, `${monitor.neuronId} ${monitor.kind} spike count`);
      for (let i = 0; i < actual.length; i++) assert.ok(Math.abs(actual[i] - monitor.nativeTimesMs[i]) <= report.criteria.maximumSpikeTimingErrorMs,
        `${monitor.neuronId} ${monitor.kind}: spike-time disagreement`);
    }
    for (let contact = 0; contact < result.recordings.length; contact++) {
      const actual = result.recordings[contact].neuralUv, native = reference.nativeRecordingUv[contact];
      assert.equal(actual.length, native.length);
      const error = max(Array.from(actual, (value, i) => Math.abs(value - native[i])));
      assert.ok(error <= report.criteria.extracellularMaximumErrorUv, `Contact ${contact + 1}: native EAP error ${error} µV`);
      for (const [field, nativeField] of [['graftUv','nativeGraftRecordingUv'],['hostUv','nativeHostRecordingUv']]) {
        const source = result.recordings[contact][field], nativeSource = reference[nativeField][contact];
        assert.equal(source.length, nativeSource.length);
        const sourceError = max(Array.from(source, (value, i) => Math.abs(value - nativeSource[i])));
        assert.ok(sourceError <= report.criteria.sourceComponentMaximumErrorUv, `${field} contact ${contact + 1}: native source error ${sourceError} µV`);
      }
    }
  });
}
