from pathlib import Path
import csv,json,io,os,shutil
from playwright.sync_api import sync_playwright
p=Path(__file__).resolve().parent.parent
url=(p/'index.html').as_uri()
results=[]
with sync_playwright() as pw:
 exe=os.environ.get('CHROME_BIN') or str(p.parents[2]/'production-equipment-qa/runtime/chrome-bin/chrome');
  # CHROME_BIN may point to any local Chromium binary.
 b=pw.chromium.launch(executable_path=exe if Path(exe).is_file() else None,args=['--no-sandbox','--no-proxy-server','--disable-gpu','--disable-dev-shm-usage'])
 for tag,opts in [('desktop',dict(viewport={'width':1365,'height':932})),('mobile',pw.devices['iPhone 13'])]:
  opts=dict(opts);opts.pop('default_browser_type',None)
  ctx=b.new_context(**opts,accept_downloads=True)
  page=ctx.new_page(); errs=[]; requests=[]; checks=[]
  page.on('pageerror',lambda e:errs.append(str(e)));page.on('request',lambda req:requests.append(req.url))
  page.goto(url,wait_until='load')
  def ok(cond,n):
   assert cond,(tag,n);checks.append(n)
  ok('Not yet tested'==page.locator('#testBadge').inner_text(),'fresh specimen explicitly not tested')
  ok(page.locator('#csv').is_disabled() and page.locator('#baseline').is_disabled(),'pre-audit export gate')
  ok(page.locator('#diam').is_disabled() and page.locator('#cover').is_disabled(),'process-gated geometry and defect inputs')
  for i in range(7): page.locator('#next').click()
  ok(page.locator('#stageTitle').inner_text().startswith('08 /'),'all eight stations traversable')
  ok(page.locator('#testBadge').inner_text().startswith('8 / 8'),'normal identity map')
  page.locator('#baseline').click()
  page.locator('#site').select_option('7');page.locator('#fault').select_option('bridge')
  ok('6 / 8' in page.locator('#testBadge').inner_text(),'wrapped D8–D1 bridge reduces correct paths')
  ok(page.locator('#matrix tbody tr').nth(7).locator("td").nth(0).get_attribute('class')=='wrong','off-diagonal C8 to D1 observed')
  page.locator('#inspection').select_option('3')
  ok('D4' in page.locator('#diagnosticTitle').inner_text() and page.locator('#site').input_value()=='7','view selection independent of defect target')
  page.locator('#fault').select_option('frame')
  ok('7 / 8' in page.locator('#testBadge').inner_text() and page.locator('#matrix tbody tr').nth(7).locator('td').last.get_attribute('class')=='wrong','frame fault still has physical disc path')
  page.locator('#fault').select_option('open')
  ok('7 / 8' in page.locator('#testBadge').inner_text(),'open joint loss propagated')
  page.locator('#fault').select_option('swap')
  ok('6 / 8' in page.locator('#testBadge').inner_text(),'connector permutation detected')
  page.locator('#clear').click()
  page.locator('#inspection').select_option('7')
  page.locator('#cover').fill('50')
  ok('50.0%' in page.locator('#aperturegate').inner_text() and 'FAIL' in page.locator('#aperturegate').inner_text() and '8 / 8' in page.locator('#testBadge').inner_text(),'masked face fails optics while the metal net is connected')
  page.locator('#diam').fill('1.5')
  ok(float(page.locator('#len').inner_text().split()[0])>31.1,'inert mandrel changes computed axial span')
  page.locator('#flat').click()
  ok(page.locator('#rot').is_disabled() and page.locator('#flat').get_attribute('aria-pressed')=='true','unwrapped projection')
  page.locator('#volume').click();page.locator('#rot').fill('87')
  ok('87°'==page.locator('#rout').inner_text(),'cylinder rotation')
  page.locator('#site').select_option('7');page.locator('#fault').select_option('frame')
  with page.expect_download() as ej:page.locator('#export').click()
  rr=json.loads(Path(ej.value.path()).read_text())
  ok(rr['current']['settings']['fault']=='frame' and rr['baseline']['continuity']['passCount']==8 and rr['difference']['mapDelta']==[8],'downloadable JSON reproduces current specimen, baseline and diff')
  with page.expect_download() as ec:page.locator('#csv').click()
  rows=list(csv.DictReader(io.StringIO(Path(ec.value.path()).read_text())))
  ok(len(rows)==8 and rows[7]['to_frame']=='1' and rows[7]['to_D8']=='1' and rows[7]['classification']=='Frame short','UTF-8 CSV contains exact test matrix')
  with page.expect_download() as eo:page.locator('#obj').click()
  obj=Path(eo.value.path()).read_text();ok(obj.count('Nominal_Platinum_Disc')==8 and obj.count('Assumed_Obstruction_Witness')==1 and 'millimetres' in obj,'true-scale offline OBJ with separate nominal discs and explicit assumed obstruction')
  page.locator('#evidence details.compare').first.locator('summary').click()
  ok('SWITCH, 2023:' in page.locator('#evidence').inner_text(),'read-only later device comparison separate')
  ok(page.evaluate('document.documentElement.scrollWidth<=window.innerWidth'),'no root horizontal overflow')
  page.evaluate('window.scrollTo(0,0)');page.screenshot(path=str(p/'validation'/f'{tag}.png'),full_page=True)
  page.locator('#reset').click()
  ok(page.locator('#testBadge').inner_text()=='Not yet tested' and page.locator('#fault').input_value()=='none' and page.locator('#site').input_value()=='0','reset actually erases specimen, faults and baseline')
  ok(not errs and all(v.startswith('file:') for v in requests),'no browser errors or external resources')
  results.append({'environment':tag,'browser':'Chromium '+b.version,'viewport':opts['viewport'],'mobile_emulation':tag=='mobile','passed':len(checks),'checks':checks,'externalRequests':[],'errors':errs});ctx.close()
 b.close()
print([(r['environment'],r['passed']) for r in results]);(p/'validation/browser.json').write_text(json.dumps(results,indent=2)+'\n')
