import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const paths = [
  'interface-contract.js','interface-experiment.js','interface-field.js','interface-presets.js',
  'interface-comparison.js','interface-comparison-analysis.js',
  'active-cable.js','active-channels.js','extra-channels.js','active-morphology.js','model-library.js',
].map(file => `src/lib/cortex/${file}`);
const sourceHashes = Object.fromEntries(await Promise.all(paths.map(async path =>
  [path, createHash('sha256').update(await readFile(new URL('../' + path, import.meta.url))).digest('hex')])));
const manifest = { version: 'cortex-interface-engine-manifest/1', algorithm: 'SHA-256', sourceHashes };
const output = `// Generated by scripts/interface-manifest.mjs. Regenerate when listed sources change.\nexport const INTERFACE_ENGINE_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;
await writeFile(new URL('../src/lib/cortex/interface-build-manifest.js', import.meta.url), output);
console.log(`Recorded ${paths.length} interface engine source fingerprints.`);
