import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const route = '/simulations/retinal-implant/prima/';
const html = read(`dist${route}index.html`);
const methods = read(`dist${route}methods/index.html`);
assert.match(html, /retinal-implant\/\?technology=photovoltaic/);
assert.doesNotMatch(html, /astro-island|data-prima-lab/);
const unified=read('dist/simulations/retinal-implant/index.html');
assert.match(unified,/data-retina-lab/);assert.match(unified,/PRIMA · photovoltaic/);
assert.match(methods, /ProViSim v2\.0\.0/);
assert.match(methods, /homogeneous.*half-space/);
assert.match(methods, /noncompact spatial tails/);
assert.match(methods, /not patient validation/);
assert.match(methods, /20\/417/);
assert.match(methods, /non-cryptographic label/);
assert.match(methods, /26 serious adverse events in 19 participants/);
assert.match(methods, /10\.5281\/zenodo\.19212252/);

const files = readdirSync(new URL('dist/_astro/', root)).filter(path => path.endsWith('.js'));
assert(files.some(path => path.includes('UnifiedRetinaLaboratory')), 'One unified UI must be emitted.');
assert(!files.some(path => path.includes('PrimaLaboratory')), 'Retired PRIMA UI must not be emitted.');
assert(files.some(path => /^worker[-.]/.test(path) && read('dist/_astro/' + path).includes('prima-1.0.0')), 'Retained PRIMA engine must be in the numerical worker.');
assert(files.some(path => read('dist/_astro/' + path).includes('rtl-webgl')), 'Shared 3D renderer must be emitted.');
assert(!read('dist/simulations/index.html').includes('href="'+route+'"'), 'No competing PRIMA catalog entry.');
assert(read('dist/devices/177-science-prima-subretinal-photovoltaic-implant/index.html').includes('/simulations/retinal-implant/?technology=photovoltaic'), 'PRIMA device links to unified mode.');
const search=JSON.parse(read('dist/search-index.json'));
assert(!JSON.stringify(search).includes('"'+route+'"'), 'No retired laboratory in search.');
assert.match(read('dist/_redirects'),/retinal-implant\/prima\/ \/simulations\/retinal-implant\/\?technology=photovoltaic 301/);
assert.match(read('scripts/prima-reference/vendor/provisim/LICENSE'), /MIT License/);
assert.match(read('scripts/prima-reference/vendor/provisim/PROVENANCE.md'), /c3cecdeeb2cb4afcd14ba591a3b285354c6be45d719fc3244912363fef0f9a13/);
console.log('PRIMA build verified: routes, scientific disclosures, hydration, numerical worker, 3D renderer, catalog, search, cross-links and retained reference license.');
