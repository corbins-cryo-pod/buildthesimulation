// Pure SI-domain electronics model. No hidden waveform, browser, headset or hardware interfaces.
export const LSB=20/65536, LIMIT=250000;
const num=x=>typeof x==='number'&&Number.isFinite(x);
const safeId=s=>typeof s==='string'&&s.length>0&&s.length<=128&&!/[\u0000-\u001f]/.test(s);
export function calibration(){return {schema:'bts.analog-waveform.v1',sampleId:'CAL-RAMP-12',revision:0,t0S:0,dtS:.001,channels:[{id:'cal-out',unit:'V',samples:Array.from({length:13},(_,i)=>-12+2*i)}],provenance:{type:'simulated',source:'External ideal calibration fixture; supplied ramp knots, not generated by ADC'}}}
export function state(){return {power:true,usb:true,connected:true,firstInput:0,rateHz:1000,input:calibration(),result:null}}
export function validate(w){
 if(!w||w.schema!=='bts.analog-waveform.v1'||!safeId(w.sampleId)||!Number.isSafeInteger(w.revision)||w.revision<0||w.revision>=Number.MAX_SAFE_INTEGER)throw Error('Expected bts.analog-waveform.v1, a sample ID and nonnegative revision.');
 if(!num(w.dtS)||w.dtS<=0||(w.t0S!==undefined&&!num(w.t0S)))throw Error('Invalid source clock: dtS must be positive; t0S must be finite.');
 if(!Array.isArray(w.channels)||!w.channels.length||w.channels.length>8)throw Error('Connect 1–8 voltage channels.');
 const ids=new Set(),n=w.channels[0]?.samples?.length;
 if(!(Number.isInteger(n)&&n>=2&&n*w.channels.length<=LIMIT))throw Error('Source requires at least two points and at most 250,000 total values.');
 for(const c of w.channels){if(!c||!safeId(c.id)||ids.has(c.id)||c.unit!=='V'||!Array.isArray(c.samples)||c.samples.length!==n||!c.samples.every(num))throw Error('Channels require unique IDs, volts, equal lengths and finite samples.');ids.add(c.id)}
 return w
}
export function digitize(v){if(!num(v))throw Error('Non-finite source voltage.');const code=Math.max(-32768,Math.min(32767,Math.round(v/LSB)))||0;return {code,volts:code*LSB,over:v< -10?-1:v>10?1:0}}
export function acquire(s){
 if(!s.power||!s.usb||!s.connected)throw Error('Not ready: turn on power, connect the USB host and connect an analog source.');
 if(!num(s.rateHz)||s.rateHz<1||s.rateHz>500000)throw Error('Rate must be from 1 through 500,000 Hz.');
 const w=validate(s.input),n=w.channels[0].samples.length,first=s.firstInput;
 if(!Number.isInteger(first)||first<0||first+w.channels.length>8)throw Error('The selected channel map does not fit AI0–AI7.');
 const last=(n-1)*w.dtS*s.rateHz;const N=1+Math.floor(last+8*Number.EPSILON*Math.max(1,last));
 if(!Number.isSafeInteger(N)||N<1||N*w.channels.length>LIMIT)throw Error('Record exceeds the teaching station’s 250,000 converted-value limit. Lower the rate.');
 const t0=w.t0S??0,dt=1/s.rateHz;if(!num(t0+(N-1)*dt)||(N>1&&t0===t0+dt))throw Error('Timebase cannot be represented safely.');
 const channels=w.channels.map((c,k)=>{const codes=[],samples=[],overload=[];for(let i=0;i<N;i++){
  const t=Math.max(0,Math.min(n-1,i/(s.rateHz*w.dtS))),a=Math.floor(t),fraction=t-a;
  const v=fraction===0?c.samples[a]:c.samples[a]*(1-fraction)+c.samples[Math.min(n-1,a+1)]*fraction;
  const m=digitize(v);codes.push(m.code);samples.push(m.volts);overload.push(m.over)
 }return {id:c.id,terminal:'AI'+(first+k),unit:'V',samples,codes,overload}});
 return {schema:'bts.analog-waveform.v1',sampleId:w.sampleId,parentRevision:w.revision,revision:w.revision+1,t0S:t0,dtS:dt,channels,provenance:{source:'10-02',type:'simulated',configuration:'Digidata 1550B, no ANC',method:'ideal signed 16-bit round-to-nearest converter; interpolation linear between source knots; no anti-alias filter',lsbV:LSB,sourceDtS:w.dtS,sourceT0S:t0,sourceProvenance:w.provenance??null}}
}
// Mutations shared by keyboard, mouse, touch, and XR adapter. Invalid actions cannot retain an old export.
export function act(s,a,p){
 s.result=null;
 if(a==='run'){s.result=acquire(s);return s.result}
 if(a==='power'||a==='usb'||a==='connected'){s[a]=!s[a];return}
 if(a==='rate'){s.rateHz=p;return}
 if(a==='map'){s.firstInput=p;return}
 if(a==='source'){s.input=null;s.input=validate(p);return}
 throw Error('Unknown control action.');
}
export function csv(r){if(!r)throw Error('No acquisition to export.');
 const ch=r.channels,fields=['time_s',...ch.flatMap((c,i)=>['ai'+i+'_V','ai'+i+'_signed_code','ai'+i+'_overload'])];
 for(let k=0;k<ch.length;k++)fields.splice(1+3*k,3,ch[k].terminal+'_V',ch[k].terminal+'_signed_code',ch[k].terminal+'_overload');
 return [fields.join(','),...ch[0].codes.map((_,i)=>[r.t0S+i*r.dtS,...ch.flatMap(c=>[c.samples[i],c.codes[i],c.overload[i]])].join(','))].join('\n')+'\n'
}
